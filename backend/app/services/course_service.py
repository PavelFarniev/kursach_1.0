def build_course_slides(course: Course) -> list[CourseSlideResponse]:
    ordered_slides = sorted(course.slides, key=lambda slide: slide.order_index)
    return [
        CourseSlideResponse(
            id=str(slide.id),
            title=slide.title,
            summary=slide.summary,
            theory_blocks=list(slide.theory_blocks or []),
            bullets=list(slide.bullets or []),
            example=slide.example,
            practice_task=slide.practice_task,
        )
        for slide in ordered_slides
    ]


def serialize_course_detail(course: Course) -> CourseDetailResponse:
    return CourseDetailResponse(
        id=course.id,
        title=course.title,
        description=course.description,
        category=course.category,
        level=course.level,
        lessons_count=course.lessons_count,
        estimated_hours=course.estimated_hours,
        slides=build_course_slides(course),
    )


def list_courses(
    db: Session,
    *,
    search: str | None = None,
    category: str | None = None,
    level: str | None = None,
) -> list[Course]:
    statement = select(Course).order_by(Course.id.asc())

    if search:
        normalized = f"%{search.strip()}%"
        statement = statement.where(or_(Course.title.ilike(normalized), Course.description.ilike(normalized)))

    if category and category != "all":
        statement = statement.where(Course.category == category)

    if level and level != "all":
        statement = statement.where(Course.level == level)

    return list(db.scalars(statement))


def get_course_by_id(db: Session, course_id: int) -> Course | None:
    return db.scalar(select(Course).options(selectinload(Course.slides)).where(Course.id == course_id))
